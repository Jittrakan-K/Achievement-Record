  function tidy(s) {
    return s.replace(/\s{2,}/g, ' ')
      .replace(/\s+([,.:;!?)\]%])/g, '$1')
      .replace(/([(\[])\s+/g, '$1')
      .replace(/\(\s*\)/g, '')
      .trim();
  }
  function bilingual(core) {
    // "Thai text (ENGLISH)" or "ENGLISH (Thai text)" → keep the English part
    var m = core.match(/^([^()A-Za-z]*[฀-๿][^()A-Za-z]*?)\s*\(([^()฀-๿]*[A-Za-z][^()฀-๿]*)\)\s*([:]?)$/);
    if (m) return m[2].trim() + m[3];
    m = core.match(/^([^()฀-๿]*[A-Za-z][^()฀-๿]*?)\s*\(([^()]*[฀-๿][^()]*)\)\s*([:]?)$/);
    if (m) return m[1].trim() + m[3];
    return null;
  }

  /* returns translated string, or null when it still contains unknown Thai */
  function translate(raw, allowPartial) {
    if (!raw || !TH.test(raw)) return null;
    var key = raw + (allowPartial ? '\u0001' : '');
    if (key in cache) return cache[key];
    var lead = (raw.match(/^\s*/) || [''])[0], trail = (raw.match(/\s*$/) || [''])[0];
    var body = raw.trim().replace(/\s+/g, ' ');
    var pre = (body.match(PREFIX_RE) || [''])[0];
    var core = body.slice(pre.length);
    var dash = core.match(/^(--\s*)(.*?)(\s*--)$/);
    if (dash) core = dash[2];
    var out = null;
    if (EXACT.hasOwnProperty(core)) out = EXACT[core];
    else if (EXACT.hasOwnProperty(body)) { out = EXACT[body]; pre = ''; }
    if (out === null) {
      var bi = bilingual(core);
      if (bi !== null && !TH.test(bi)) out = bi;
    }
    if (out === null) {
      var s = core;
      RULES.forEach(function (r) { s = s.replace(r[0], r[1]); });
      s = s.replace(PHRASE_RE, function (m) { return ' ' + phraseMap[m] + ' '; });
      s = tidy(s);
      if (!TH.test(s) || allowPartial) out = s;
    }
    if (out !== null && dash) out = '-- ' + out + ' --';
    var res = out === null ? null : (lead || (TH.test(raw.charAt(0)) ? ' ' : '')) + (pre ? pre.replace(/\s*$/, ' ') : '') + out + (trail || (TH.test(raw.charAt(raw.length - 1)) ? ' ' : ''));
    if (res !== null && !raw.match(/^\s/) && !pre && !lead && res.charAt(0) === ' ' && !raw.match(/^[฀-๿]/)) res = res.slice(1);
    cache[key] = res;
    return res;
  }
